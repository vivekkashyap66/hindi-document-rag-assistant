"""Run the six mandatory assignment queries and save real pipeline outputs."""
from pathlib import Path

from src.answer import extractive_answer, format_result
from src.retriever import HindiRetriever
from src.config import TOP_K, ROOT_DIR

QUERIES = [
    "SLV-III ने किस उपग्रह को कक्षा में स्थापित किया और किस वर्ष?",
    "कलाम को भारत रत्न किस वर्ष प्राप्त हुआ?",
    "पोखरण-II में कलाम की क्या भूमिका थी?",
    "Which institution did Kalam attend to study aeronautical engineering?",
    "Who co-wrote the autobiography, and in what year was it published?",
    "How and where did Kalam die in 2015?",
]


def main():
    retriever = HindiRetriever()
    output_path = ROOT_DIR / "outputs" / "results.md"
    blocks = ["# Mandatory Test Query Results", "",
              "Generated by the actual retrieval pipeline. Inspect answers and citations before submission.", ""]
    for i, query in enumerate(QUERIES, start=1):
        hits = retriever.retrieve(query, TOP_K)
        answer = extractive_answer(query, hits)
        block = f"## Test {i}\n\n" + format_result(query, answer, hits)
        print(block)
        blocks.append(block)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text("\n\n---\n\n".join(blocks) + "\n", encoding="utf-8")
    print(f"\nSaved results to: {output_path}")


if __name__ == "__main__":
    main()
